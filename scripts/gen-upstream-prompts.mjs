import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const pkgDir = join(root, '.audit', 'upstream', 'extracted', 'package');
const outPath = join(root, 'src', 'generated', 'upstream-prompts.ts');
const mod = await import(pathToFileURL(join(pkgDir, 'build', 'prompts', 'index.js')).href);
let out = '// GENERATED by scripts/gen-upstream-prompts.mjs from @z_ai/mcp-server@0.1.4 build/prompts\n// Do not edit by hand.\n\n';
const names = [];
for (const [key, value] of Object.entries(mod)) {
  names.push(key);
  if (typeof value === 'string') {
    out += `export const ${key}: string = ${JSON.stringify(value)};\n\n`;
  } else if (value && typeof value === 'object') {
    out += `export const ${key}: Record<string, string> = ${JSON.stringify(value)};\n\n`;
  }
}
out += `export const UPSTREAM_PROMPT_EXPORTS: string[] = ${JSON.stringify(names)};\n`;
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.log(`generated ${outPath} (${names.length} exports)`);