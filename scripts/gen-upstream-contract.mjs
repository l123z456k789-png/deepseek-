import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const fixturePath = join(root, 'tests', 'fixtures', 'upstream', 'tools-list.json');
const outPath = join(root, 'src', 'generated', 'upstream-tools.ts');
const list = JSON.parse(readFileSync(fixturePath, 'utf8'));
const tools = list.result.tools.map((t) => {
  const props = t.inputSchema.properties ?? {};
  const required = new Set(t.inputSchema.required ?? []);
  const params = Object.entries(props).map(([name, p]) => ({
    name,
    type: p.type ?? 'string',
    description: p.description ?? '',
    enum: p.enum ?? null,
    required: required.has(name),
  }));
  return { name: t.name, description: t.description, params };
});
const ts = `// GENERATED by scripts/gen-upstream-contract.mjs from tests/fixtures/upstream/tools-list.json
// Do not edit by hand.

export interface UpstreamParam {
  name: string;
  type: string;
  description: string;
  enum: string[] | null;
  required: boolean;
}

export interface UpstreamToolDef {
  name: string;
  description: string;
  params: UpstreamParam[];
}

export const UPSTREAM_TOOL_DEFS: UpstreamToolDef[] = ${JSON.stringify(tools, null, 2)};
`;
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, ts);
console.log(`generated ${outPath} (${tools.length} tools)`);